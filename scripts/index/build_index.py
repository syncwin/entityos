#!/usr/bin/env python3
"""Build the derived D1 index from the Markdown+YAML files (files are canonical; files win).

Parses and schema-checks claims and sources (reusing scripts/validate.py), then writes one SQL file
that fully rebuilds the index tables. Load it into LOCAL D1 with:

    wrangler d1 execute entityos-db --local --file <out.sql>      (run from worker/)

Defaults index the fake examples. A private instance passes its own vault paths.
Stdlib + pyyaml only (same as validate.py).
"""
import argparse
import datetime
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import validate as v  # noqa: E402  (scripts/validate.py)

ROOT = v.ROOT


def q(x):
    """SQL literal."""
    if x is None:
        return "NULL"
    return "'" + str(x).replace("'", "''") + "'"


def body_of(p):
    m = re.match(r"---\r?\n.*?\r?\n---\r?\n?(.*)", p.read_text(encoding="utf-8"), re.S)
    return (m.group(1) if m else "").strip()


def load_dir(directory, schema, errs):
    rows = []
    for p in sorted(Path(directory).glob("*.md")):
        d = v.front_matter(p)
        if d is None:
            errs.append(f"{p.name}: no YAML front matter")
            continue
        errs.extend(v.check(d, schema, p.name))
        rows.append((p.name, d, body_of(p)))
    return rows


def build(owner_path, claims_dir, sources_dir):
    errs = []
    owner = yaml.safe_load(Path(owner_path).read_text(encoding="utf-8"))
    errs += v.check(owner, v.load("schema/owner.schema.json"), "owner")
    entities = owner.get("entities", []) if isinstance(owner, dict) else []
    entity_ids = {e.get("id") for e in entities if isinstance(e, dict)}
    claims = load_dir(claims_dir, v.load("schema/claim.schema.json"), errs)
    sources = load_dir(sources_dir, v.load("schema/source.schema.json"), errs)
    all_ids = [e.get("id") for e in entities] + [d.get("id") for _, d, _ in claims + sources]
    dup = sorted({i for i in all_ids if all_ids.count(i) > 1})
    if dup:
        errs.append(f"ids not globally unique: {dup}")
    for name, d, _ in claims + sources:
        if d.get("entity_id") not in entity_ids:
            errs.append(f"{name}: entity_id {d.get('entity_id')!r} not in owner entities")
    source_ids = {d.get("id") for _, d, _ in sources}
    for name, d, _ in claims:
        if d.get("source_id") not in source_ids:
            errs.append(f"{name}: source_id {d.get('source_id')!r} not found in sources")
    if errs:
        return None, errs, (0, 0, 0)

    out = ["-- Generated by scripts/index/build_index.py. Full rebuild of the derived index; do not edit.",
           "BEGIN TRANSACTION;", "DELETE FROM search_fts;", "DELETE FROM claims;", "DELETE FROM sources;", "DELETE FROM entities;",
           "DELETE FROM index_meta;"]
    for e in entities:
        out.append(f"INSERT INTO entities (id, type, name) VALUES ({q(e['id'])}, {q(e['type'])}, {q(e['name'])});")
    for _, d, body in sources:
        out.append(
            "INSERT INTO sources (id, entity_id, title, url, type, status, verified_at, body) VALUES "
            f"({q(d['id'])}, {q(d['entity_id'])}, {q(d['title'])}, {q(d.get('url'))}, {q(d['type'])}, "
            f"{q(d.get('status'))}, {q(d.get('verified_at'))}, {q(body)});")
        text = " ".join(x for x in (d["title"], d.get("url") or "", body) if x)
        out.append(f"INSERT INTO search_fts (id, entity_id, type, text) VALUES ({q(d['id'])}, {q(d['entity_id'])}, 'source', {q(text)});")
    for _, d, body in claims:
        out.append(
            "INSERT INTO claims (id, entity_id, statement, status, source_id, verified_at, body) VALUES "
            f"({q(d['id'])}, {q(d['entity_id'])}, {q(d['statement'])}, {q(d['status'])}, {q(d['source_id'])}, "
            f"{q(d.get('verified_at'))}, {q(body)});")
        text = " ".join(x for x in (d["statement"], body) if x)
        out.append(f"INSERT INTO search_fts (id, entity_id, type, text) VALUES ({q(d['id'])}, {q(d['entity_id'])}, 'claim', {q(text)});")
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    out.append(f"INSERT INTO index_meta (key, value) VALUES ('rebuilt_at', {q(stamp)});")
    out.append("COMMIT;")
    return "\n".join(out) + "\n", [], (len(entities), len(sources), len(claims))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--owner", default=str(ROOT / "config/owner.example.yaml"))
    ap.add_argument("--claims", default=str(ROOT / "examples/claims"))
    ap.add_argument("--sources", default=str(ROOT / "examples/sources"))
    ap.add_argument("--out", default=str(ROOT / "worker/.wrangler/index.local.sql"))
    a = ap.parse_args()
    sql, errs, counts = build(a.owner, a.claims, a.sources)
    if errs:
        print("FAIL")
        print("\n".join(errs))
        return 1
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(sql, encoding="utf-8")
    print(f"wrote {out}: {counts[0]} entities, {counts[1]} sources, {counts[2]} claims")
    return 0


if __name__ == "__main__":
    sys.exit(main())
